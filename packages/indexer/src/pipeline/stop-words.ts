/**
 * Checks if a normalized term is present in the stop words dictionary.
 */
export function isStopWord(
  term: string,
  customStopWords?: Set<string> | ReadonlySet<string>,
): boolean {
  if (!term) return false;
  const wordSet = customStopWords ?? DEFAULT_STOP_WORDS;
  return wordSet.has(term.toLowerCase());
}
